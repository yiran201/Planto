// 静态节假日数据（REQ-011，REQ-071 补 2027 年）。浏览器端没有可用的免费
// 节假日 API，也不允许本工具在运行时联网抓取官方节假日安排（会引入不受控
// 的外部依赖），这里是手动维护的静态表，数据来源见文件末尾（写入时都用
// WebSearch 核对过官方/权威信息源，不是凭记忆编的）。这是纯手工维护的
// 数据，没有自动更新机制，往后每年都需要照着当年官方通知/权威信息源补一
// 份新的表进来，这是这份静态数据方案本身的局限。
//
// 中国大陆 2027 年数据缺失是刻意的，不是漏补：中国的法定节假日"放假+
// 调休"具体安排（哪几天连休、哪个周末补班）由国务院办公厅每年临时发文
// 公布，历史上一般在上一年的 10~12 月才发布（2026 年这份是 2025-11-04
// 发的），写这份数据时（2026-08）官方还没公布 2027 年的具体安排，只有
// 元旦/春节/国庆节这几个节日本身的公历日期是已知的——但没有"放假调休"
// 这个数据，日历标不出来，不能凭空猜/编。等官方正式公布后（预计
// 2026 年底前后），需要再补一次这份表；美国联邦假日和日本国民の祝日
// 不受这个限制——美国假日由固定法律规则决定（多数是"每月第 N 个星期几"
// 加上"落在周末就顺延/提前到最近工作日"这条通用规则），日本假日由
// 《国民の祝日に関する法律》和天文台的春分/秋分推算日期决定，两者都可以
// 提前多年准确算出，REQ-071 已经把 2027 年这两个地区的数据补齐。
//
// 范围：只做"日历视图上标出来"（月/周/日视图的"休"/"班"角标）。原本这里
// 还说明了这份数据不参与自动排程算法的避让逻辑，但那套自动排程子系统
// （domain/scheduler.js、dayPlanner.planWeekDays）在 REQ-052 已经整个
// 删除，不再有相关取舍需要说明。

export const HOLIDAY_TYPE = { HOLIDAY: 'holiday', WORKDAY: 'workday' };

export const SUPPORTED_REGIONS = ['CN', 'US', 'JP'];

function range(dates, name, type = HOLIDAY_TYPE.HOLIDAY) {
  const entries = {};
  for (const d of dates) entries[d] = { name, type };
  return entries;
}

