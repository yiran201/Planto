// dateKey 是 utils/dateUtils.getDateKey() 产出的 'YYYY-MM-DD' 格式。
// 查不到（地区没数据、或者这个地区在这一年没收录——比如中国大陆目前
// 只到 2026 年）时返回 null，调用方按"这天没有特殊标记"处理，不是错误。
export function getHolidayInfo(dateKey, region) {
  const year = Number(dateKey.slice(0, 4));
  return HOLIDAYS_BY_REGION[region]?.[year]?.[dateKey] || null;
}

